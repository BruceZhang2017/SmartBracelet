package com.yourapp.health.female.data.model

/**
 * 心情状态常量
 * 对应DailySymptomData中的mood字段
 */
object MoodLevel {
    const val NONE = 0       // 未选择
    const val CALM = 1       // 平静
    const val HAPPY = 2      // 开心
    const val RELAXED = 3    // 放松
    const val ENERGETIC = 4  // 活力满满
    const val SENSITIVE = 5  // 敏感
    const val ANXIOUS = 6    // 焦躁
    const val IRRITABLE = 7  // 易怒
    const val SAD = 8        // 悲伤
}
